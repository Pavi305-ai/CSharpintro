
using System;

class Datatypes
{
    static void datatypes(string[] args)
    {
        int age = 22;
        Console.WriteLine("Integer value: " + age);

        float height = 5.5f;
        Console.WriteLine("Float value: " + height);

        double salary = 25000.75;
        Console.WriteLine("Double value: " + salary);

        decimal amount = 500.50m;
        Console.WriteLine("Decimal value: " + amount);

        char grade = 'A';
        Console.WriteLine("Character value: " + grade);

        string name = "Pavithra";
        Console.WriteLine("String value: " + name);

        bool isPassed = true;
        Console.WriteLine("Boolean value: " + isPassed);
    }
}
